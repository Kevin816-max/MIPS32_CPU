# 初始化数据
ORI $1, $0, 0x5678  # $1 = 0x00005678 (正数)
ORI $2, $0, 1       # $2 = 1
SUB $2, $0, $2      # $2 = -1 (0xFFFFFFFF, 用于测试算术右移的符号位填充)

# 执行移位，结果存入 $4, $5, $6
SLL $4, $1, 4       # $4 = $1 左移4位 -> 0x00056780
SRL $5, $1, 4       # $5 = $1 逻辑右移4位 -> 0x00000567
SRA $6, $2, 4       # $6 = $2 算术右移4位 -> 0xFFFFFFFF (符号位1被保留)

# 结尾死循环
NOP
NOP